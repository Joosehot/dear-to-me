// ---------------- the language in use ----------------

export type Lang = 'fi' | 'en';
const TABLES: Record<Lang, Text> = { fi, en };
export const LANGS: { lang: Lang; name: string }[] = [
  { lang: 'fi', name: 'Suomi' },
  { lang: 'en', name: 'English' },
];

function first(): Lang {
  try {
    const saved = localStorage.getItem('d2m.lang');
    if (saved === 'fi' || saved === 'en') return saved;
  } catch {
    // no storage: the browser's language decides
  }
  return navigator.language.toLowerCase().startsWith('fi') ? 'fi' : 'en';
}

let current: Lang = first();
document.documentElement.lang = current;
const listeners = new Set<() => void>();

export function lang() {
  return current;
}

/** Change the language: every text follows at once (the app redraws), and it is remembered. */
export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
  try {
    localStorage.setItem('d2m.lang', l);
  } catch {
    // remembered for this page only
  }
  listeners.forEach((f) => f());
}

export function onLang(f: () => void) {
  listeners.add(f);
  return () => {
    listeners.delete(f);
  };
}

/** The texts in the current language. */
export const t: Text = new Proxy({} as Text, {
  get: (_, key) => TABLES[current][key as keyof Text],
});
